export function getTranslation(lang: Language, key: keyof typeof translations['kaa'], params?: Record<string, string | number>): string {
  const dictionary = translations[lang] || translations.kaa;
  let text = (dictionary[key] || translations.kaa[key] || key) as string;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return text;
}
